/**
 * Demo listings are generated relative to the current date so the prototype
 * always has live offers, expired ones and sold-out ones to show.
 */
export function buildDemoListings(now: Date = new Date()): Listing[] {
  return TEMPLATES.map((t) => {
    const day = addDays(now, t.day);
    const start = atTime(day, t.from);
    const end = atTime(day, t.to);
    const bestBefore = atTime(addDays(now, t.bestBeforeInDays), 23, 59);
    return {
      id: t.id,
      sellerType: t.sellerType,
      sellerId: t.sellerId,
      locationId: t.locationId,
      title: t.title,
      titleEn: t.titleEn,
      categorySlug: t.categorySlug,
      description: t.description,
      descriptionEn: t.descriptionEn,
      image: "",
      originalPrice: t.originalPrice,
      discountedPrice: t.discountedPrice,
      quantity: t.quantity,
      quantityInitial: t.quantityInitial,
      unit: t.unit,
      estimatedWeightKg: t.estimatedWeightKg,
      dateLabelType: t.dateLabelType,
      bestBeforeDate: bestBefore.toISOString(),
      pickupDeadline: end.toISOString(),
      pickupWindowStart: start.toISOString(),
      pickupWindowEnd: end.toISOString(),
      allergens: t.allergens,
      storageRequirements: t.storage,
      status: t.status ?? "active",
      isSurpriseBag: t.isSurpriseBag,
      createdAt: addDays(now, t.day - 1).toISOString(),
      updatedAt: addDays(now, t.day - 1).toISOString(),
      demo: true,
    } satisfies Listing;
  });
}
